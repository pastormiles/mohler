GITHUB_REPO = "pastormiles/mohler"
GITHUB_API_CACHE_TTL = 300  # 5 minutes

_github_cache = {'data': None, 'timestamp': 0}


def fetch_github_workflow_runs(limit=5):
    """Fetch recent GitHub Actions workflow runs with caching."""
    global _github_cache

    now = time.time()

    # Return cached data if fresh
    if _github_cache['data'] and (now - _github_cache['timestamp']) < GITHUB_API_CACHE_TTL:
        return _github_cache['data']

    try:
        url = f"https://api.github.com/repos/{GITHUB_REPO}/actions/runs"
        headers = {
            'Accept': 'application/vnd.github.v3+json',
            'User-Agent': 'AlbertMohler-Admin-Dashboard'
        }

        response = requests.get(url, headers=headers, params={'per_page': limit}, timeout=10)

        if response.status_code == 404:
            return {'error': 'Repository not found or not public', 'runs': []}

        if response.status_code == 403:
            # Rate limited - return cached data if available
            if _github_cache['data']:
                _github_cache['data']['error'] = 'GitHub API rate limit exceeded (using cached data)'
                return _github_cache['data']
            return {'error': 'GitHub API rate limit exceeded', 'runs': []}

        response.raise_for_status()
        data = response.json()

        runs = []
        for run in data.get('workflow_runs', [])[:limit]:
            # Calculate duration
            created = datetime.fromisoformat(run['created_at'].replace('Z', '+00:00'))
            updated = datetime.fromisoformat(run['updated_at'].replace('Z', '+00:00'))
            duration_seconds = int((updated - created).total_seconds())

            runs.append({
                'id': run['id'],
                'name': run['name'],
                'status': run['status'],
                'conclusion': run['conclusion'],
                'created_at': run['created_at'],
                'updated_at': run['updated_at'],
                'html_url': run['html_url'],
                'duration_seconds': duration_seconds,
                'duration_text': format_duration(duration_seconds)
            })

        result = {
            'runs': runs,
            'fetched_at': datetime.utcnow().isoformat(),
            'error': None
        }

        # Update cache
        _github_cache = {'data': result, 'timestamp': now}

        return result

    except requests.RequestException as e:
        # Return cached data if available
        if _github_cache['data']:
            _github_cache['data']['error'] = f'GitHub API error (using cached data): {str(e)}'
            return _github_cache['data']
        return {'error': str(e), 'runs': []}


def format_duration(seconds):
    """Format duration in human-readable form."""
    if seconds < 60:
        return f"{seconds}s"
    elif seconds < 3600:
        minutes = seconds // 60
        secs = seconds % 60
        return f"{minutes}m {secs}s"
    else:
        hours = seconds // 3600
        minutes = (seconds % 3600) // 60
        return f"{hours}h {minutes}m"


