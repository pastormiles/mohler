def calculate_vector_trend(snapshots, current_count=None):
    """Calculate vector count trend from snapshots."""
    if not snapshots and current_count is None:
        return {'current': 0, 'change_7d': 0, 'change_text': 'No data'}

    current = current_count if current_count is not None else (snapshots[0]['count'] if snapshots else 0)

    # Find snapshot from ~7 days ago
    week_ago = datetime.utcnow() - timedelta(days=7)
    week_ago_count = current

    for snap in snapshots:
        if snap['timestamp']:
            ts_str = snap['timestamp']
            if ts_str.endswith('Z'):
                ts_str = ts_str[:-1] + '+00:00'
            elif '+' not in ts_str and '-' not in ts_str[-6:]:
                ts_str = ts_str + '+00:00'
            try:
                ts = datetime.fromisoformat(ts_str)
                if ts.replace(tzinfo=None) <= week_ago:
                    week_ago_count = snap['count']
                    break
            except ValueError:
                continue

    change = current - week_ago_count
    change_text = f"+{change}" if change >= 0 else str(change)

    return {
        'current': current,
        'change_7d': change,
        'change_text': f"{current:,} vectors ({change_text} this week)"
    }


def get_pipeline_health_summary(workflow_runs):
    """Calculate pipeline health summary from workflow runs."""
    if not workflow_runs:
        return {
            'status': 'unknown',
            'status_text': 'No workflow data',
            'last_success': None,
            'days_since_success': None
        }

    # Find last successful run
    last_success = None
    for run in workflow_runs:
        if run.get('conclusion') == 'success':
            last_success = run
            break

    # Determine overall status
    latest = workflow_runs[0]
    if latest.get('status') == 'in_progress':
        status = 'running'
        status_text = 'Pipeline running'
    elif latest.get('conclusion') == 'success':
        status = 'healthy'
        status_text = 'Pipeline healthy'
    elif latest.get('conclusion') == 'failure':
        status = 'failed'
        status_text = 'Last run failed'
    else:
        status = 'unknown'
        status_text = f"Status: {latest.get('conclusion') or latest.get('status')}"

    # Calculate days since last success
    days_since_success = None
    if last_success:
        success_time_str = last_success['created_at'].replace('Z', '+00:00')
        success_time = datetime.fromisoformat(success_time_str)
        days_since_success = (datetime.now(timezone.utc) - success_time).days

    return {
        'status': status,
        'status_text': status_text,
        'last_success': last_success['created_at'] if last_success else None,
        'days_since_success': days_since_success
    }


